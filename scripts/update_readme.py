"""Rebuild README.md (counts, problem table, theme index) from the problem folders.

Run after LeetSync adds problems:   python scripts/update_readme.py
Check without writing:              python scripts/update_readme.py --check
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER_RE = re.compile(r"^(\d+)-(.+)$")
DIFF_RE = re.compile(r"Difficulty-(Easy|Medium|Hard)")
TITLE_RE = re.compile(r"<h2><a [^>]*>(.*?)</a></h2>")

# Themes are matched on the problem title, so they are facts about the problem, not opinions.
THEMES = [
    ("Parentheses and brackets", ("parenthes", "bracket", "brace")),
    ("Non-overlapping selections", ("non-overlapping",)),
    ("Subsequences", ("subsequence",)),
]


def load_problems() -> list[dict]:
    problems = []
    for folder in ROOT.iterdir():
        m = FOLDER_RE.match(folder.name)
        if not (folder.is_dir() and m):
            continue
        readme = (folder / "README.md").read_text(encoding="utf-8") if (folder / "README.md").exists() else ""
        diff = DIFF_RE.search(readme)
        title = TITLE_RE.search(readme)
        py = sorted(folder.glob("*.py"))
        problems.append({
            "num": int(m.group(1)),
            "folder": folder.name,
            "title": title.group(1) if title else m.group(2).replace("-", " ").title(),
            "difficulty": diff.group(1) if diff else "Unknown",
            "solution": f"{folder.name}/{py[0].name}" if py else None,
        })
    return sorted(problems, key=lambda p: p["num"])


def render(problems: list[dict]) -> str:
    counts = {d: sum(p["difficulty"] == d for p in problems) for d in ("Easy", "Medium", "Hard")}
    solved = sum(p["solution"] is not None for p in problems)
    out = [
        "# LeetCode solutions",
        "",
        "[![CI](https://github.com/DINESH-7S/leetcode/actions/workflows/ci.yml/badge.svg)]"
        "(https://github.com/DINESH-7S/leetcode/actions/workflows/ci.yml)",
        "",
        "My LeetCode solutions in Python. Each folder has the problem statement and my solution. "
        "Solutions are synced from LeetCode with LeetSync, and the lists below are generated by "
        "`scripts/update_readme.py`.",
        "",
        f"**{len(problems)} problems** ({counts['Easy']} easy, {counts['Medium']} medium, {counts['Hard']} hard), "
        f"{solved} with solutions uploaded",
        "",
        "## By theme",
        "",
    ]
    for name, keys in THEMES:
        members = [p for p in problems if any(k in p["title"].lower() for k in keys)]
        if members:
            links = ", ".join(f"[{p['num']}]({p['folder']})" for p in members)
            out.append(f"- **{name}** ({len(members)}): {links}")
    out += ["", "## All problems", "", "| # | Problem | Difficulty | Solution |", "|---|---------|------------|----------|"]
    for p in problems:
        sol = f"[Python]({p['solution']})" if p["solution"] else "not uploaded yet"
        out.append(f"| {p['num']} | [{p['title']}]({p['folder']}) | {p['difficulty']} | {sol} |")
    return "\n".join(out) + "\n"


def main() -> int:
    new = render(load_problems())
    target = ROOT / "README.md"
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != new:
            print("README.md is out of date; run scripts/update_readme.py")
            return 1
        return 0
    target.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
